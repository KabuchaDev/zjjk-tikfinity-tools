import assert from 'node:assert/strict';
import {EventRouter} from './event-router.mjs';
let time=100000;const config={commentCooldownSeconds:8,giftMappings:{'123':{side:'blue',kind:'elite',count:2}}};
const router=new EventRouter(config,()=>time);
const chat=(comment,userId='1',msgId=String(time))=>({event:'chat',data:{comment,userId,uniqueId:'Viewer',msgId}});
assert.equal(router.route(chat(' RONALDO ')).side,'red');
assert.equal(router.route(chat('messi','1','next')),null);
assert.equal(router.route(chat('messi','2','2')).side,'blue');
time+=8000;
assert.equal(router.route(chat('messi','1','next')).side,'blue');
assert.equal(router.route(chat('ronaldo','3','next')),null);
assert.equal(router.route(chat('messi run stop','4')),null);
assert.equal(router.route(chat('hello','5')),null);
assert.equal(router.route({event:'like',data:{userId:'1'}}),null);
assert.equal(router.route({event:'chat',data:{comment:'messi'}}),null);
assert.equal(router.route({event:'gift',data:{userId:'1',giftId:123,giftType:1,repeatEnd:false}}),null);
assert.equal(router.route({event:'gift',data:{userId:'1',giftId:123,giftType:1,repeatEnd:true,repeatCount:3,msgId:'gift-final'}}).count,6);
assert.equal(router.route({event:'gift',data:{userId:'1',giftId:123,giftType:1,repeatEnd:true,repeatCount:3,msgId:'gift-final'}}),null);
const injected=router.route({event:'chat',data:{comment:'messi',userId:'malicious',uniqueId:'evil\nstop @a',msgId:'new'}});
assert.equal(injected.command,'jjkarena spawn blue basic 1 evil_stop__a');
console.log('PASS: routing, case/space normalization, per-user cooldown, deduplication, gift streaks, unknown events, command injection prevention.');
